// Generates web-cursors.json: carets exactly as the web's y-prosemirror cursor plugin puts them
// into awareness (`absolutePositionToRelativePosition` + `Y.relativePositionToJSON`), with the
// Yjs document they point into. Run with yjs, y-prosemirror and prosemirror-* installed:
//   npm i yjs@13 y-prosemirror@1.3.7 prosemirror-model prosemirror-state prosemirror-view prosemirror-transform
//   node make-web-cursors.mjs > web-cursors.json
import * as Y from "yjs";
import { Schema } from "prosemirror-model";
import { initProseMirrorDoc, absolutePositionToRelativePosition } from "y-prosemirror";

const schema = new Schema({
  nodes: {
    doc: { content: "title block+" },
    title: { content: "inline*", attrs: { blockId: { default: null } } },
    paragraph: { content: "inline*", group: "block", attrs: { blockId: { default: null } } },
    text: { group: "inline" },
  },
});

const doc = new Y.Doc();
doc.clientID = 4242;
const content = doc.getXmlFragment("content");
const blocks = [
  ["title", "01a1ac00-0000-7000-8000-000000000001", "Заметка"],
  ["paragraph", "01a1ac00-0000-7000-8000-000000000002", "Hello brave new world"],
  ["paragraph", "01a1ac00-0000-7000-8000-000000000003", ""],
  ["paragraph", "01a1ac00-0000-7000-8000-000000000004", "Последний"],
];
doc.transact(() => {
  content.insert(0, blocks.map(([type, id, text]) => {
    const el = new Y.XmlElement(type);
    el.setAttribute("blockId", id);
    if (text) el.insert(0, [new Y.XmlText(text)]);
    return el;
  }));
});

const { doc: pm, mapping } = initProseMirrorDoc(content, schema);
// Start of each block's content in the ProseMirror document.
const starts = [];
pm.forEach((node, offset) => starts.push(offset + 1));
const at = (block, offset) => starts[block] + offset;

const cases = [
  { name: "inside text", block: 1, offset: 6 },
  { name: "end of a paragraph", block: 1, offset: 21 },
  { name: "start of a paragraph", block: 1, offset: 0 },
  { name: "empty paragraph", block: 2, offset: 0 },
  { name: "selection", block: 1, offset: 6, headBlock: 3, headOffset: 4 },
];

const out = cases.map((c) => {
  const anchor = absolutePositionToRelativePosition(at(c.block, c.offset), content, mapping);
  const head = absolutePositionToRelativePosition(at(c.headBlock ?? c.block, c.headOffset ?? c.offset), content, mapping);
  const state = { user: { name: "Веб", color: "#7A4FD6", account: "acc-web" }, cursor: { anchor: Y.relativePositionToJSON(anchor), head: Y.relativePositionToJSON(head) } };
  return { name: c.name, state: JSON.stringify(state), anchor: { block: c.block, offset: c.offset }, head: { block: c.headBlock ?? c.block, offset: c.headOffset ?? c.offset } };
});

console.log(JSON.stringify({
  note: "Generated by make-web-cursors.mjs (yjs 13, y-prosemirror 1.3.7). Blocks are top-level indexes; offsets are UTF-16.",
  update: Buffer.from(Y.encodeStateAsUpdate(doc)).toString("base64"),
  cases: out,
}, null, 2));
