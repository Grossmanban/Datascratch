#!/usr/bin/env bash
# Generates Datascratch.xcodeproj with XcodeGen.
# Local packages (Packages/DSCore, DSEditor, DSDesign) are owned by other
# streams and may not exist yet; only the ones present are linked. The app
# falls back to built-in stand-ins (`#if canImport(...)`) for missing ones.
set -euo pipefail
cd "$(dirname "$0")/.."

out=project.packages.yml
{
  echo "# Generated by scripts/generate.sh — do not edit."
  found=()
  for pkg in DSCore DSEditor DSDesign; do
    if [ -f "Packages/$pkg/Package.swift" ]; then found+=("$pkg"); fi
  done
  # The DSEditor ↔ DSCore adapter is a separate package inside DSEditor.
  if [ -f "Packages/DSEditor/CoreAdapter/Package.swift" ] && [ -f "Packages/DSCore/Package.swift" ]; then
    found+=("DSEditorCore")
  fi
  if [ ${#found[@]} -eq 0 ]; then
    echo "packages: {}"
  else
    echo "packages:"
    for pkg in "${found[@]}"; do
      echo "  $pkg:"
      if [ "$pkg" = "DSEditorCore" ]; then
        echo "    path: Packages/DSEditor/CoreAdapter"
      else
        echo "    path: Packages/$pkg"
      fi
    done
    echo "targets:"
    echo "  Datascratch:"
    echo "    dependencies:"
    for pkg in "${found[@]}"; do
      echo "      - package: $pkg"
    done
  fi
} > "$out"

echo "Linked packages: $(grep -c '^      - package' "$out" || true)"
xcodegen generate --spec project.yml
